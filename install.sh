#!/usr/bin/env bash
# Installs the core only. Package manager modules are fetched on demand.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"

printf '%s\n' "${C_GREEN}======================================"
printf '%s\n' "        SYSUP INSTALLER v$SYSUP_VERSION"
printf '%s\n' "           by FilBanfi"
printf '%s\n' "======================================${C_RESET}"
echo ""

# ===== VERIFY SOURCES =====
for required in sysup.sh sysup-install.sh sysup-remove.sh sysup-uninstall.sh \
                lib/common.sh plugin.conf.example \
                modules/core.sh modules/modules.sh modules/template.sh; do
    if [[ ! -e "$SCRIPT_DIR/$required" ]]; then
        err "Incomplete source tree: missing '$required'."
        err "Run install.sh from the root of the cloned repository."
        exit 1
    fi
done

# ===== DIRS =====
info "Creating directories..."
mkdir -p "$SYSUP_INSTALL_DIR" "$SYSUP_BIN_DIR"

# ===== COPY =====
info "Copying core files..."
cp "$SCRIPT_DIR/sysup.sh" \
   "$SCRIPT_DIR/sysup-install.sh" \
   "$SCRIPT_DIR/sysup-remove.sh" \
   "$SCRIPT_DIR/sysup-uninstall.sh" \
   "$SCRIPT_DIR/sysup-help.sh" \
   "$SCRIPT_DIR/plugin.conf.example" \
   "$SYSUP_INSTALL_DIR/"

mkdir -p "$SYSUP_INSTALL_DIR/lib" "$SYSUP_INSTALL_DIR/modules"
cp "$SCRIPT_DIR/lib/common.sh" "$SYSUP_INSTALL_DIR/lib/"
cp "$SCRIPT_DIR/modules/core.sh" \
   "$SCRIPT_DIR/modules/modules.sh" \
   "$SCRIPT_DIR/modules/template.sh" \
   "$SYSUP_INSTALL_DIR/modules/"

if [[ ! -f "$SYSUP_INSTALL_DIR/sysup.sh" || ! -f "$SYSUP_INSTALL_DIR/lib/common.sh" ]]; then
    err "Installation failed: core files missing."
    exit 1
fi

# ===== CONFIG =====
# Never overwrite an existing plugin.conf: it belongs to the user.
if [[ ! -f "$SYSUP_INSTALL_DIR/plugin.conf" ]]; then
    cp "$SYSUP_INSTALL_DIR/plugin.conf.example" "$SYSUP_INSTALL_DIR/plugin.conf"
    ok "plugin.conf created."
else
    warn "plugin.conf already exists: left untouched."
fi

# ===== PERMISSIONS =====
chmod +x "$SYSUP_INSTALL_DIR/"*.sh
find "$SYSUP_INSTALL_DIR/modules" -type f -name '*.sh' -exec chmod +x {} +

# ===== COMMANDS =====
# Wrappers, not symlinks: with a symlink BASH_SOURCE[0] would be ~/.local/bin/sysup
# and the core would look for lib/ and plugin.conf in the bin directory.
# Also avoids readlink -f, which is not guaranteed on BSD/macOS.
make_wrapper() {
    local name="$1" target="$2"
    cat > "$SYSUP_BIN_DIR/$name" <<EOF
#!/usr/bin/env bash
# Generated by sysup install.sh - do not edit.
exec "$target" "\$@"
EOF
    chmod +x "$SYSUP_BIN_DIR/$name"
}

info "Creating commands..."
make_wrapper sysup           "$SYSUP_INSTALL_DIR/sysup.sh"
make_wrapper sysup-install   "$SYSUP_INSTALL_DIR/sysup-install.sh"
make_wrapper sysup-remove    "$SYSUP_INSTALL_DIR/sysup-remove.sh"
make_wrapper sysup-uninstall "$SYSUP_INSTALL_DIR/sysup-uninstall.sh"
make_wrapper sysup-help      "$SYSUP_INSTALL_DIR/sysup-help.sh"
ok "Commands created in $SYSUP_BIN_DIR"

# ===== PATH =====
# The marker makes removal trivial and safe later on.
if [[ ":$PATH:" != *":$SYSUP_BIN_DIR:"* ]]; then
    info "Configuring PATH..."
    added=0
    for rc in "$HOME/.bashrc" "$HOME/.zshrc"; do
        if [[ -f "$rc" ]] && ! grep -Fq '# sysup-path' "$rc"; then
            printf '\n# Added by sysup installer\nexport PATH="%s:$PATH" # sysup-path\n' \
                "$SYSUP_BIN_DIR" >> "$rc"
            ok "PATH added to $(basename "$rc")"
            added=1
        fi
    done
    if (( added == 0 )); then
        warn "No .bashrc/.zshrc modified: add $SYSUP_BIN_DIR to your PATH manually."
    fi
else
    ok "$SYSUP_BIN_DIR is already in PATH."
fi

echo ""
printf '%s\n' "${C_GREEN}======================================"
printf '%s\n' "       INSTALLATION COMPLETED"
printf '%s\n' "======================================${C_RESET}"
echo ""
echo "Commands: sysup | sysup-install | sysup-remove | sysup-uninstall | sysup-help"
echo ""
echo "Next: install the modules you need with 'sysup-install [module]'"
echo ""
echo "Then edit $SYSUP_INSTALL_DIR/plugin.conf to set the execution order."